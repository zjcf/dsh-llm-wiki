import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, rm, symlink } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { unzlibSync } from 'fflate';
import { Wiki } from '../dist/wiki.js';
import { handler, API } from '../dist/api.js';
import { extract } from '../dist/extract.js';
import { imageDocx, imagePdf, tinyPng } from './image-fixtures.mjs';

test('PDF 内嵌和内联图片转 PNG，Word 保留段落中的图片位置', async () => {
  const pdf = await extract('fixture.pdf', imagePdf());
  assert.equal(pdf.images.length, 2, JSON.stringify(pdf.limitations));
  const encoded = Buffer.from(pdf.images[0].bytes);
  assert.equal(encoded.readUInt32BE(16), 2);
  assert.equal(encoded.readUInt32BE(20), 2);
  const length = encoded.readUInt32BE(33);
  assert.deepEqual([...unzlibSync(encoded.subarray(41, 41 + length))], [0, 255, 0, 0, 0, 255, 0, 0, 0, 0, 255, 255, 255, 255]);
  assert.match(pdf.text, /第 1 页[\s\S]*image-proof-pdf[\s\S]*!\[/);
  const docx = await extract('fixture.docx', imageDocx());
  assert.equal(docx.images.length, 1);
  assert.deepEqual(Buffer.from(docx.images[0].bytes), tinyPng);
  assert.match(docx.text, /image-proof-before[\s\S]*段落 2[\s\S]*!\[[\s\S]*image-proof-after/);
});

test('只保留 Agent 放入正文的图片，不自动追加图库；补抽取不改写知识页', async t => {
  const root = await mkdtemp(join(tmpdir(), 'wiki-images-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const wiki = new Wiki(root); await wiki.initialize();
  const { record } = await wiki.import('fixture.docx', imageDocx());
  const result = await wiki.review({ id: record.id, title: '图片验证', body: '已有知识正文', status: 'partial' });
  const source = await wiki.source(record.id);
  assert.match(source.images[0].markdown, /\.\.\/\.\.\/extracted\/assets\//);
  const page = await wiki.page(result.pageId);
  assert.doesNotMatch(page.body, /来源图片|!\[/);
  const body = '## 操作\n\n第一步\n\n' + source.images[0].markdown + '\n\n第二步';
  await wiki.review({ id: record.id, title: '图片验证', body, status: 'partial' });
  assert.match((await wiki.page(result.pageId)).body, /第一步[\s\S]*!\[[\s\S]*第二步/);
  const originalPage = await readFile(join(root, result.pageId), 'utf8');
  assert.match(await readFile(join(root, record.reader), 'utf8'), /assets\/s-[a-f0-9]{16}\/image-1.png/);
  const request = handler(wiki);
  const url = path => 'http://localhost' + API + '?' + new URLSearchParams({ op: 'image', id: result.pageId, path });
  const asset = await request(new Request(url('../../' + source.images[0].path)));
  assert.equal(asset.status, 200); assert.equal(asset.headers.get('content-type'), 'image/png');
  assert.deepEqual(Buffer.from(await asset.arrayBuffer()), tinyPng);
  for (const path of ['../../.wiki/manifest.json', '../../../../etc/passwd', 'https://evil.invalid/image.png', '../../extracted/assets/' + record.id + '/unknown.png', '../../extracted/assets/' + record.id + '/%2e%2e%2fsecret.png']) assert.equal((await request(new Request(url(path)))).status, 404);
  const manifest = JSON.parse(await readFile(join(root, '.wiki/manifest.json'), 'utf8'));
  delete manifest.sources[record.id].extraction_version; delete manifest.sources[record.id].images;
  await writeFile(join(root, '.wiki/manifest.json'), JSON.stringify(manifest));
  const manualReader = '# 人工核验版\n\n<span id="P0001"></span>已核对的证据锚点\n';
  await writeFile(join(root, record.reader), manualReader);
  await wiki.historyRecordExternal((await wiki.historyExternalPreview()).token);
  await wiki.upgradeExtractions(); await wiki.upgradeExtractions();
  assert.equal(await readFile(join(root, record.reader), 'utf8'), manualReader);
  const upgraded = await wiki.source(record.id);
  assert.equal(upgraded.sha256, record.sha256); assert.equal(upgraded.status, 'partial'); assert.equal(upgraded.images.length, 1);
  assert.equal(await readFile(join(root, result.pageId), 'utf8'), originalPage);
  assert.deepEqual((await wiki.check()).errors, []);
  const assetPath = join(root, upgraded.images[0].path);
  await rm(assetPath); await symlink(join(root, 'index.md'), assetPath);
  assert.equal((await request(new Request(url('../../' + upgraded.images[0].path)))).status, 400);
  await rm(assetPath); await writeFile(assetPath, tinyPng);
  const { token } = await wiki.previewDeletion(record.id); await wiki.deleteSource(record.id, token);
  await assert.rejects(readFile(assetPath), { code: 'ENOENT' });
  assert.equal((await request(new Request(url('../../' + upgraded.images[0].path)))).status, 404);
});
